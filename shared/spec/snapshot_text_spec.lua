local text = require("shared.snapshot.text")

describe("shared/snapshot/text.lua", function()
  it("escapes separators, percent and control characters, and round trips", function()
    assert.are.equal("a%2Cb%3Bc%25d%0Ae%09", text.escape("a,b;c%d\ne\t"))
    for _, sample in ipairs({ "", "plain", "a,b;c%d", "line\nbreak\r\t", "%41", "Ωmega, ünï;" }) do
      local escaped = text.escape(sample)
      assert.is_nil(escaped:find("[,;%c]"))
      assert.are.equal(sample, text.unescape(escaped))
    end
  end)

  it("splits on a plain separator and keeps empty parts", function()
    assert.are.same({ "" }, text.split("", ";"))
    assert.are.same({ "a", "b", "c" }, text.split("a;b;c", ";"))
    assert.are.same({ "a", "", "" }, text.split("a;;", ";"))
    assert.are.same({ "a", "b" }, text.split("a.b", "."))
  end)

  it("writes numbers with 17 significant digits", function()
    assert.are.equal("0.10000000000000001", text.number(0.1))
    assert.are.equal("1", text.number(1))
    assert.are.equal(0.1, tonumber(text.number(0.1)))
  end)

  describe("clean_name", function()
    it("trims and returns a good name", function()
      assert.are.equal("Verse 2", text.clean_name("  Verse 2 \t"))
    end)
    it("refuses empty", function()
      assert.are.same({ nil, "empty_name" }, { text.clean_name("") })
      assert.are.same({ nil, "empty_name" }, { text.clean_name("   ") })
      assert.are.same({ nil, "empty_name" }, { text.clean_name(nil) })
    end)
    it("refuses control characters and invalid UTF-8", function()
      assert.are.same({ nil, "bad_name" }, { text.clean_name("a\nb") })
      assert.are.same({ nil, "bad_name" }, { text.clean_name("a\255b") })
    end)
    it("counts characters against MAX_NAME", function()
      assert.are.equal(40, text.MAX_NAME)
      assert.are.equal(("é"):rep(40), text.clean_name(("é"):rep(40)))
      assert.are.same({ nil, "name_too_long" }, { text.clean_name(("é"):rep(41)) })
    end)
  end)

  it("finds an entry by name and numbers the next id", function()
    local list = { { id = 3, name = "A" }, { id = 7, name = "B" } }
    local entry, position = text.find(list, "B")
    assert.are.equal(7, entry.id)
    assert.are.equal(2, position)
    assert.is_nil(text.find(list, "C"))
    assert.are.equal(8, text.next_id(list))
    assert.are.equal(1, text.next_id({}))
  end)
end)
